// ---- Seeded RNG helpers ----
// String -> 32-bit unsigned seed
function xmur3(str: string) {
  let h = 1779033703 ^ str.length;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  return function () {
    h = Math.imul(h ^ (h >>> 16), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return h >>> 0;
  };
}

// 32-bit seed -> RNG that returns float in [0, 1)
function mulberry32(seed: number) {
  let a = seed >>> 0;
  return function () {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// ---- Deterministic shuffle ----
export function shuffleWithSeed<T>(
  input: readonly T[],
  seed: string | number,
): T[] {
  const seedStr = typeof seed === "number" ? String(seed) : seed;
  const seedFn = xmur3(seedStr);
  const rng = mulberry32(seedFn()); // deterministic for a given seedStr

  const arr = input.slice(); // copy
  // Fisher–Yates
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}
